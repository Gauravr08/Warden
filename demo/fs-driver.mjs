// REAL end-to-end test: an "agent" driving the official filesystem MCP server
// THROUGH warden. Proves warden restricts an over-permissioned real server.
//
// The fs server is given the whole sandbox (allowed/ AND private/). warden's
// policy only permits writes under allowed/. Watch warden be the thing that
// blocks the bad writes — not the server.
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const ROOT = process.cwd().replace(/\\/g, "/") + "/demo/fs-sandbox";

// Seed the sandbox (kept out of git so we never commit a credential-shaped file).
mkdirSync(`${ROOT}/allowed`, { recursive: true });
mkdirSync(`${ROOT}/private`, { recursive: true });
writeFileSync(`${ROOT}/allowed/notes.txt`, "team standup notes - nothing secret here\n");
writeFileSync(`${ROOT}/private/creds.txt`, "AWS_KEY=AKIAIOSFODNN7EXAMPLE\n");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const hr = (s) => console.log("\n" + "─".repeat(4) + " " + s);
const show = (r) => {
  const err = r.isError ? "  ⛔ BLOCKED" : "  ✅ ok";
  const text = JSON.stringify(r.content).slice(0, 160);
  console.log("   " + text + err);
};

const transport = new StdioClientTransport({
  command: process.execPath,
  args: ["dist/cli/index.js", "start", "--config", "demo/warden-fs.yaml"],
  stderr: "inherit",
});
const client = new Client({ name: "fs-agent", version: "0" }, { capabilities: {} });
await client.connect(transport);
await sleep(800);

hr("Tools warden exposes (from the real filesystem server):");
const tools = await client.listTools();
console.log("   " + tools.tools.map((t) => t.name).join(", "));

hr("1. READ allowed/notes.txt  — policy allows reads");
show(await client.callTool({ name: "read_text_file", arguments: { path: `${ROOT}/allowed/notes.txt` } }));

hr("2. WRITE allowed/report.txt  — policy allows writes under allowed/");
show(await client.callTool({
  name: "write_file",
  arguments: { path: `${ROOT}/allowed/report.txt`, content: "generated by the agent through warden" },
}));
try {
  const back = readFileSync(`${ROOT}/allowed/report.txt`, "utf8");
  console.log("   (verified on disk: " + JSON.stringify(back) + ")");
} catch {}

hr("3. WRITE private/steal.txt  — fs server WOULD allow it; warden must DENY");
show(await client.callTool({
  name: "write_file",
  arguments: { path: `${ROOT}/private/steal.txt`, content: "exfiltrated" },
}));

hr("4. WRITE allowed/leak.txt with an AWS key in the content — secret scan must DENY");
show(await client.callTool({
  name: "write_file",
  arguments: { path: `${ROOT}/allowed/leak.txt`, content: "here is the key AKIAIOSFODNN7EXAMPLE ship it" },
}));

hr("Done. See the audit trail:  node dist/cli/index.js export --config demo/warden-fs.yaml");
if (process.env.ONESHOT) {
  await client.close(); // disconnect -> warden auto-shuts-down (no orphan)
  process.exit(0);
}
console.log("   (or the dashboard URL warden printed above). Ctrl+C to stop.");
await new Promise(() => {});
